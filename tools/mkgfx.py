#!/usr/bin/env python3
"""Convert the pictures for the build (python standard library only).

  title: Koala file -> bitmap, screen, colour binaries + background colour
  map:   Art Studio hires file -> raw deflate of bitmap and of screen data

usage: mkgfx.py title.kla map.art outdir
"""
import sys
import zlib


def deflate(data):
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    z = c.compress(data) + c.flush()
    assert zlib.decompress(z, -15) == data
    return z


# Mouse arrow, 24x21 sprite. '#' = black outline, '.' = white fill.
ARROW = """
#
##
#.#
#..#
#...#
#....#
#.....#
#......#
#.......#
#........#
#.....#####
#..#..#
#.# #..#
##  #..#
#    #..#
     #..#
      ##
""".strip("\n").split("\n")


def sprite(ch):
    out = bytearray(63)
    for y, row in enumerate(ARROW):
        for x, c in enumerate(row):
            if c == ch:
                out[y * 3 + x // 8] |= 0x80 >> (x % 8)
    return bytes(out)


def main():
    kla, art, out = sys.argv[1:4]

    # sprite 0 = fill, sprite 1 = outline (sprite 0 is drawn in front)
    open(out + "/cursor.bin", "wb").write(sprite(".") + sprite("#"))

    d = open(kla, "rb").read()
    assert len(d) == 10003, "not a Koala file: %s" % kla
    d = d[2:]
    open(out + "/title_bmp.bin", "wb").write(d[0:8000])
    open(out + "/title_scr.bin", "wb").write(d[8000:9000])
    open(out + "/title_col.bin", "wb").write(d[9000:10000])
    open(out + "/title.inc", "w").write(
        "; generated by tools/mkgfx.py - do not edit\nTITLE_BG = %d\n" % (d[10000] & 15))

    d = open(art, "rb").read()
    assert len(d) >= 9002, "not an Art Studio hires file: %s" % art
    d = d[2:]
    zb = deflate(d[0:8000])
    zs = deflate(d[8000:9000])
    open(out + "/map_bmp.z", "wb").write(zb)
    open(out + "/map_scr.z", "wb").write(zs)
    print("mkgfx: map bitmap %d bytes, map screen %d bytes" % (len(zb), len(zs)))


if __name__ == "__main__":
    main()
